// Render the rows data/ loads into the SQL that worker/scripts/seed.ts writes to seed.sql.
//
// Production tables reference data rows by id: receipts, reports → goals; receipts, generations,
// screenings → actions (ids are stable and never reused, data/ids.md). A `DELETE FROM goals` with such a
// row present fails D1's foreign-key check on the remote path even under `PRAGMA defer_foreign_keys`
// (deploy run 42303908649 on 2026-11-06, the first merge after the first production generation), so
// goals and actions are upserted by id and only ids that left data/ are deleted. The other five tables
// are referenced by nothing outside this seed and are deleted and re-inserted, children before parents.
import { createHash } from 'node:crypto';
import type { Rows } from '../src/load';

type Row = Record<string, unknown>;

/**
 * The stamp `seed-remote.ts` compares with `meta.seed_sha256` to skip a reseed when data/ is unchanged.
 * It covers the rows, not the SQL text, and drops `updated_at`: `loadRows` stamps the render time into
 * every goal, so a hash over the raw rows changed on every run and the skip never fired (sixteen merges
 * on 2026-11-09 each reseeded and used up the free tier's daily row writes).
 */
export function seedHash(rows: Rows): string {
  return createHash('sha256')
    .update(JSON.stringify(rows, (k, v: unknown) => (k === 'updated_at' ? undefined : v)))
    .digest('hex');
}
const q = (v: unknown): string => (v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${String(v).replace(/'/g, "''")}'`);
const cols = (o: Row) => Object.keys(o).map((k) => `"${k}"`).join(',');
const vals = (o: Row) => Object.values(o).map(q).join(',');

const insert = (table: string, objs: Row[]): string[] => objs.map((o) => `INSERT INTO ${table} (${cols(o)}) VALUES (${vals(o)});`);

/** Insert, or update every non-id column of the row that already holds this id. */
const upsert = (table: string, objs: Row[]): string[] =>
  objs.map((o) => {
    const set = Object.keys(o).filter((k) => k !== 'id').map((k) => `"${k}" = excluded."${k}"`).join(', ');
    return `INSERT INTO ${table} (${cols(o)}) VALUES (${vals(o)}) ON CONFLICT(id) DO UPDATE SET ${set};`;
  });

/** Drop the rows whose id is no longer in data/ (an id with production references fails here, by design: retire it instead). */
const deleteStale = (table: string, objs: Row[]): string => `DELETE FROM ${table} WHERE id NOT IN (${objs.map((o) => q(o.id)).join(',')});`;

export const REPLACED_TABLES = ['positions', 'district_offices', 'members_elect', 'members', 'states'] as const;
export const UPSERTED_TABLES = ['goals', 'actions'] as const;

export function renderSeedSql(rows: Rows, now: string): string {
  const goals = rows.goals as unknown as Row[], actions = rows.actions as unknown as Row[];
  return [
    '-- generated by worker/scripts/seed.ts; do not edit',
    `DELETE FROM ${REPLACED_TABLES.join('; DELETE FROM ')};`,
    ...upsert('goals', goals),
    ...upsert('actions', actions),
    deleteStale('actions', actions),
    deleteStale('goals', goals),
    ...insert('members', rows.members as unknown as Row[]),
    ...insert('district_offices', rows.offices as unknown as Row[]),
    ...insert('members_elect', rows.membersElect as unknown as Row[]),
    ...insert('positions', rows.positions.map((p) => ({ ...p, changed_by: 'seed', changed_at: now }))),
    ...insert('states', rows.states as unknown as Row[]),
  ].join('\n');
}
